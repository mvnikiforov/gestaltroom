/**
 * Контент сайта.
 *
 * КАК ЗАМЕНИТЬ ФОТОГРАФИИ
 * -----------------------
 * 1. Положите файл в `public/images/` (например `public/images/anna.webp`).
 * 2. Пропишите путь к нему в поле `photo.src` ниже: путь начинается с `/`
 *    и ведёт относительно корня сайта, без `public/` в начале.
 *
 * Если картинки нет или она не загрузилась — вместо неё автоматически
 * показывается аккуратная заглушка с инициалами, так что сайт не сломается.
 *
 * Рекомендуемый формат: WebP, ширина 800–1200 px, качество 80–85,
 * соотношение сторон 4:5 (портрет), файл до 200 КБ.
 */
export interface PsychologistPhoto {
  src: string;
  alt: string;
  /** Размеры файла — чтобы браузер верно зарезервировал место до загрузки. */
  width: number;
  height: number;
}

export interface Psychologist {
  id: string;
  name: string;
  subtitle: string;
  /** Абзацы биографии, каждый элемент — отдельный абзац. */
  bio: string[];
  /** Телефон для записи. Убирается вместе с `phoneHref`, если не нужен. */
  phone?: string;
  phoneHref?: string;
  photo: PsychologistPhoto;
  /** Tailwind-классы для рубашки карточки. */
  accent: string;
  /** Tailwind-класс цвета для градиента-подсказки «есть что дочитать».
   *  Должен совпадать с фоном карточки из `accent`, иначе будет виден стык. */
  fade: string;
  /** Задержка появления карточки, мс. */
  delay: number;
}

export interface QuickStartItem {
  id: string;
  title: string;
  /** Формат встречи: «офлайн по предварительной записи», «онлайн». */
  format: string;
  /** Когда: «последнее воскресенье месяца», «каждую субботу». */
  schedule: string;
  /** Время: «13:00», «утром в 9:00». */
  time: string;
  /** Стоимость: «бесплатно», «1000 рублей». */
  price: string;
  /** Ведущие: «Мария, Валерия», «Валерия». */
  hosts: string;
  /** Необязательное пояснение под пунктом. */
  note?: string;
}

